<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff;" align="justify"><strong style=""><span style=" font-family: Arial;   font-size: 14.0000pt;">&nbsp; Standard Operation Procedures</span></strong></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">1.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">The tenure of IQAC will be for a continuous period of 2 years from the date of appointment.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">2.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">The Meeting of the IQAC will be conducted quarterly. The quorum for the meeting shall be two-third of the total number of members. Additional meetings may be held as and when required.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">3.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">Director/Secretary in consultation with the chairperson will decide the agenda and send communication to all members. The date, time, venue and agenda of the meeting will be communicated to the members at least one week in advance.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">4.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">Minutes of the meeting will be uploaded to institutional website also.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">5.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">The agenda, minutes and action taken reports will be documented in hard and soft copy formats.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">6.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">Academic and Administrative audits will be done after completion of the academic year. The Schedule of the audit will be finalized by the Chairperson after discussion with the members during the IQAC meeting. Audit reports submitted by the auditors will be sent to the departments for corrective action.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">7.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">AQAR will be prepared and discussed during the IQAC meeting. Finalized AQAR will be placed before College Council for the approval and the approved AQAR will be submitted to the NAAC after Cycle 1 of accreditation.</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Arial;  font-size: 12.0000pt;"><span style="">8.&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">The composition of IQAC shall be as follows-</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Symbol;   font-size: 10.0000pt;"><span style="">&middot;&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">Chairperson: Head of the Institution</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Symbol;   font-size: 10.0000pt;"><span style="">&middot;&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">Teachers to represent all level (Three to eight)</span></p>
<p class="MsoNormal" style="margin-bottom: 11.2500pt; margin-left: 18.0000pt; text-indent: -18.0000pt; text-align: justify; text-justify: inter-ideograph;  background: #ffffff; " align="justify"><span style="font-family: Symbol;   font-size: 10.0000pt;"><span style="">&middot;&nbsp;</span></span><span style=" font-family: Arial;  font-size: 12.0000pt;">One member from the Management</span></p>
